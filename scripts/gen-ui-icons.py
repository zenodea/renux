#!/usr/bin/env python3
"""Writes src/icons/ui_icons.zig from Material Icons Round SVGs (Apache 2.0), the set the Android app
uses through Icons.Rounded. Usage: gen-ui-icons.py <folder of downloaded 24px SVGs>

Download each with:
  curl -o NAME.svg https://fonts.gstatic.com/s/i/materialiconsround/NAME/vN/24px.svg
"""
import os, re, sys

# Kind in icons.zig -> Material icon name, and an optional SVG transform.
KINDS = [
    ("sidebar", "view_sidebar", ""),
    ("more", "more_horiz", ""),
    ("plus", "add", ""),
    ("split_right", "splitscreen", "rotate(90 12 12)"),
    ("split_down", "splitscreen", ""),
    ("float", "picture_in_picture", ""),
    ("zoom", "open_in_full", ""),
    ("close", "close", ""),
    ("terminal", "terminal", ""),
    ("server", "laptop", ""),
    ("gear", "settings", ""),
    ("palette", "palette", ""),
    ("interface", "space_dashboard", ""),
    ("keyboard", "keyboard", ""),
    ("search", "search", ""),
    ("bell", "notifications", ""),
    ("up", "keyboard_arrow_up", ""),
    ("down", "keyboard_arrow_down", ""),
    ("right", "keyboard_arrow_right", ""),
    ("new_session", "library_add", ""),
    ("add_host", "add_to_queue", ""),
    ("filter", "filter_list", ""),
    ("minimize", "remove", ""),
    ("board", "view_kanban", ""),
    ("eye", "visibility", ""),
]

folder = sys.argv[1]
out = ["//! Generated by scripts/gen-ui-icons.py from Material Icons Round (Apache 2.0), the icons",
       "//! the Android app uses. Don't edit by hand.", "",
       "pub const Icon = struct { name: []const u8, path: []const u8, transform: []const u8 };", "",
       "pub const icons = [_]Icon{"]
for kind, name, transform in KINDS:
    svg = open(os.path.join(folder, name + ".svg")).read()
    paths = [m for m in re.findall(r"<path([^>]*)/?>", svg) if 'fill="none"' not in m]
    d = " ".join(re.search(r'\bd="([^"]*)"', p).group(1) for p in paths)
    d = re.sub(r"\s+", " ", d).strip()
    out.append(f'    .{{ .name = "{kind}", .path = "{d}", .transform = "{transform}" }},')
out.append("};")
open(os.path.join(os.path.dirname(__file__), "..", "src", "icons", "ui_icons.zig"), "w").write("\n".join(out) + "\n")
